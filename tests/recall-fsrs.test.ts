import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { after, it } from "node:test";
import type { LhMessage } from "../src/core/native-messages.ts";
import { createFauxCore, fauxAssistantMessage, fauxToolCall, type ToolCall } from "@earendil-works/pi-ai";

const dir = fs.mkdtempSync(path.join(os.tmpdir(), "lh-recall-fsrs-"));
process.env.LH_DATA_DIR = dir;
after(() => { const resolved = fs.realpathSync(dir); if (!resolved.startsWith(fs.realpathSync(os.tmpdir()) + path.sep)) throw new Error("Unexpected temporary path"); fs.rmSync(resolved, { recursive: true, force: true }); });

it("requires explicit concepts and ratings, replays original times, rejects duplicates and can undo", async () => {
	const { stores } = await import("../src/server/stores.ts");
	const { collectRecallCandidates } = await import("../src/core/mistakes.ts");
	const { confirmRecallFsrs, recallFsrsReviewData, undoRecallFsrsBatch, suggestRecallMappings, recallMappingEngineOverride } = await import("../src/server/recall-fsrs.ts");
	const { readRecallFsrsEvents } = await import("../src/server/recall-fsrs-store.ts");
	const { readFlashcardsSnapshot } = await import("../src/server/graph-fsrs.ts");
	const { projectRecallFsrs } = await import("../src/core/recall-fsrs.ts");
	const { computeGraphFsrsSummary } = await import("../src/core/fsrs-graph.ts");
	const { graphView } = await import("../src/server/graph.ts");
	const { readPlannerLearningCapacityServer } = await import("../src/server/planner.ts");
	const { recallOverrideInfo, saveRecallOverride } = await import("../src/server/recall-overrides.ts");
	const route = await import("../app/api/mistakes/recall-fsrs/route.ts");
	const chat = stores.chatStore.createChat("Algebra");
	const day1 = Date.parse("2026-01-01T09:00:00Z"), day2 = Date.parse("2026-01-05T09:00:00Z"), now = Date.parse("2026-01-08T09:00:00Z");
	const messages = [
		{ role: "toolResult", toolName: "recall", toolCallId: "call1", timestamp: day1, details: { kind: "explain", questionText: "Matrix rank?", text: "An answer", committed: "A model answer", answeredAt: new Date(day1).toISOString() }, content: [] },
		{ role: "toolResult", toolName: "recall", toolCallId: "call2", timestamp: day2, details: { kind: "explain", questionText: "Matrix rank again?", text: "Another answer", committed: "A model answer", answeredAt: new Date(day2).toISOString() }, content: [] },
	] as unknown as LhMessage[];
	stores.chatStore.saveMessages(chat.id, messages);
	stores.graphStore.appendNode({ id: "node_rank", name: "Matrix rank", statement: "Rank measures dimension", aliases: [], createdAt: new Date(day1).toISOString(), provenance: [{ chatId: chat.id, messageId: "m1" }] });
	const drafts = collectRecallCandidates(chat.id, messages).map((candidate) => candidate.draft);
	assert.equal(drafts.length, 2);
	fs.writeFileSync(path.join(dir, "recall-scan.json"), JSON.stringify({ version: 1, status: "complete", total: 2, results: drafts.map((draft) => ({ id: draft.id, draft, sessionTitle: "Algebra", verdict: "partial", strengths: "", missing: "", correction: "", evidence: "", errorType: "knowledge-gap", topic: "Matrix rank", rule: "" })) }));
	const preview = recallFsrsReviewData();
	assert.equal(preview.results.length, 2);
	const model = createFauxCore({ tokenSize: { min: 64, max: 64 } });
	model.setResponses([fauxAssistantMessage([fauxToolCall("submit_recall_concept_suggestions", { items: [{ answerId: drafts[0]!.id, nodeId: "node_rank", reason: "Bài hỏi về hạng ma trận." }, { answerId: drafts[1]!.id, nodeId: "", reason: "Chưa đủ căn cứ." }] } as ToolCall["arguments"], { id: "mapping" })], { stopReason: "toolUse" })]);
	recallMappingEngineOverride.current = { model: model.getModel(), streamFn: model.streamSimple };
	const suggestions = await suggestRecallMappings(drafts.map((draft) => draft.id));
	assert.equal(suggestions.items[0]?.nodeId, "node_rank");
	assert.equal(recallFsrsReviewData().results.find((item) => item.id === drafts[0]!.id)?.aiSuggestion?.reason, "Bài hỏi về hạng ma trận.");
	assert.equal(fs.existsSync(path.join(dir, "recall-fsrs.json")), false, "AI mapping must not create a review");
	recallMappingEngineOverride.current = undefined;
	const correction = recallOverrideInfo(drafts[0]!.id);
	const savedCorrection = saveRecallOverride({ id: drafts[0]!.id, fingerprint: correction.fingerprint, expectedUpdatedAt: null, verdict: "correct", help: "independent", timerMs: 60000 });
	assert.throws(() => saveRecallOverride({ id: drafts[0]!.id, fingerprint: correction.fingerprint, expectedUpdatedAt: null, verdict: "wrong" }), /changed/);
	assert.equal(savedCorrection.verdict, "correct");
	const evidenceReport = readPlannerLearningCapacityServer({ now }).report.subjectBreakdown.find((item) => item.subject === "Algebra");
	assert.equal(evidenceReport?.recallInsights.allTime.correct, 1); assert.equal(evidenceReport?.recallInsights.allTime.partial, 1);
	assert.equal(evidenceReport?.recallInsights.allTime.confirmed, 1); assert.equal(evidenceReport?.recallInsights.allTime.timerCount, 1);
	assert.equal(fs.existsSync(path.join(dir, "recall-fsrs.json")), false, "correcting recall evidence never writes FSRS");
	assert.equal((await route.GET()).status, 200);
	assert.equal((await route.POST(new Request("http://localhost/api/mistakes/recall-fsrs", { method: "POST", headers: { "Content-Type": "application/json" }, body: JSON.stringify({ items: [{ answerId: drafts[0]!.id }] }) }))).status, 400);
	const selection = (index: number, nodeId: string, rating: number) => ({ answerId: drafts[index]!.id, nodeId, rating, answerRevision: preview.results.find((item) => item.id === drafts[index]!.id)!.revision, nodeRevision: preview.nodes.find((item) => item.id === nodeId)?.revision ?? "missing" });
	assert.equal(fs.existsSync(path.join(dir, "recall-fsrs.json")), false, "preview must not mutate data");
	assert.throws(() => confirmRecallFsrs([selection(0, "missing", 3)], now));
	assert.throws(() => confirmRecallFsrs([{ ...selection(0, "node_rank", 3), nodeRevision: "stale" }], now), /changed/);
	assert.equal(fs.existsSync(path.join(dir, "recall-fsrs.json")), false);
	// Submit in reverse order: projection must use the original chronology.
	assert.equal(confirmRecallFsrs([selection(1, "node_rank", 3), selection(0, "node_rank", 2)], now), 2);
	const events = readRecallFsrsEvents();
	const projection = projectRecallFsrs(events);
	assert.deepEqual(projection.reviews.map((review) => review.at), [day1, day2]);
	assert.equal(projection.schedules.node_rank?.reps, 2);
	assert.throws(() => confirmRecallFsrs([selection(0, "node_rank", 1)], now), /already saved/);
	const snapshot = readFlashcardsSnapshot();
	assert.equal(snapshot?.propositions?.node_rank?.schedule?.reps, 2);
	assert.equal(snapshot?.propositions?.node_rank?.recallOnly, true);
	const graph = graphView();
	assert.equal(computeGraphFsrsSummary({ nodes: graph.propositions, chains: graph.chains }, snapshot!, now).nodes.node_rank?.reps, 2, "confirmed recall changes the planner's FSRS projection");
	const capacity = readPlannerLearningCapacityServer({ now });
	assert.equal(capacity.report.dataCoverage.fsrsReviews, 2);
	assert.equal(capacity.report.dimensions.find((axis) => axis.id === "memory_consolidation")?.sampleCount, 2, "reviews and concepts are not counted as independent samples");
	assert.equal(fs.existsSync(path.join(dir, "core-plugin-data", "flashcards", "flashcards.json")), false, "no Flashcards are created");
	const batch = recallFsrsReviewData().lastBatch!;
	assert.equal(undoRecallFsrsBatch(batch.id, now + 1), 2);
	assert.equal(readFlashcardsSnapshot()?.propositions?.node_rank, undefined);
	assert.equal(readRecallFsrsEvents().length, 2, "undo retains the event audit trail");
	assert.equal(confirmRecallFsrs([selection(0, "node_rank", 3)], now + 2), 1, "an undone answer can be reviewed again");
	assert.throws(() => undoRecallFsrsBatch(batch.id, now + 3), /changed/, "an old undo must not revert a newer batch");
	const cardDir = path.join(dir, "core-plugin-data", "flashcards");
	fs.mkdirSync(cardDir, { recursive: true });
	const cardFile = path.join(cardDir, "flashcards.json");
	const card = { propositions: { node_rank: { schedule: { reps: 1 }, cues: [{}] } }, reviews: [] };
	fs.writeFileSync(cardFile, JSON.stringify(card));
	assert.equal(readFlashcardsSnapshot()?.propositions?.node_rank?.recallOnly, undefined, "a later reviewed Flashcard keeps its own schedule");
	const currentBatch = recallFsrsReviewData().lastBatch!;
	assert.equal(undoRecallFsrsBatch(currentBatch.id, now + 4), 1);
	assert.throws(() => confirmRecallFsrs([selection(0, "node_rank", 3)], now + 5), /reviewed Flashcard/);
	assert.deepEqual(JSON.parse(fs.readFileSync(cardFile, "utf8")), card, "an existing Flashcards schedule stays untouched");
	stores.chatStore.saveMessages(chat.id, [{ ...(messages[0] as object), details: { kind: "explain", questionText: "Changed question", text: "Changed answer", answeredAt: new Date(day1).toISOString() } }] as unknown as LhMessage[]);
	assert.equal(recallFsrsReviewData().results.some((result) => result.id === drafts[0]!.id), false, "stale AI assessments are not offered after an answer changes");
	const changed = readPlannerLearningCapacityServer({ now }).report.subjectBreakdown.find((item) => item.subject === "Algebra")!.recallInsights.allTime;
	assert.equal(changed.needsReview, 1); assert.equal(changed.assessed, 0, "stale grades must not be counted");
});
